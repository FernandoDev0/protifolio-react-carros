export const getCarModelName = (car: Car): string => {
  if (car.name.toLowerCase().startsWith(car.brand.toLowerCase())) {
    const trimmed = car.name.slice(car.brand.length).trim();
    if (trimmed) return trimmed;
  }
  return car.name;
};
